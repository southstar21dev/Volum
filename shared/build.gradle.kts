// iOS gets the same build-time values as androidApp's BuildConfig, from the same Gradle properties.
val generateIosBuildConfig = tasks.register("generateIosBuildConfig") {
    val versionName = providers.gradleProperty("volum.versionName")
    val pocketbaseUrl = providers.gradleProperty("volum.pocketbaseUrl").orElse("https://apivolum.southstar21.dev")
    inputs.property("versionName", versionName)
    inputs.property("pocketbaseUrl", pocketbaseUrl)
    val out = layout.buildDirectory.dir("generated/iosBuildConfig")
    outputs.dir(out)
    doLast {
        val file = out.get().file("dev/southstar21/volum/platform/IosBuildConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// GENERATED by :shared:generateIosBuildConfig from gradle.properties — do not edit.
            |package dev.southstar21.volum.platform
            |
            |internal object IosBuildConfig {
            |    const val VERSION_NAME = "${versionName.get()}"
            |    const val POCKETBASE_URL = "${pocketbaseUrl.get()}"
            |}
            |""".trimMargin(),
        )
    }
}

