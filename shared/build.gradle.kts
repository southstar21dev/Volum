// iOS gets the same build-time values as androidApp's BuildConfig, from the same Gradle properties.
val generateIosBuildConfig = tasks.register("generateIosBuildConfig") {
    val versionName = providers.gradleProperty("volum.versionName")
    val pocketbaseUrl = providers.gradleProperty("volum.pocketbaseUrl").orElse("https://apivolum.southstar21.dev")
    inputs.property("versionName", versionName)
    inputs.property("pocketbaseUrl", pocketbaseUrl)
    val out = layout.buildDirectory.dir("generated/iosBuildConfig")
    outputs.dir(out)
    doLast {
        val file = out.get().file("dev/southstar21/volum/platform/IosBuildConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// GENERATED by :shared:generateIosBuildConfig from gradle.properties — do not edit.
            |package dev.southstar21.volum.platform
            |
            |internal object IosBuildConfig {
            |    const val VERSION_NAME = "${versionName.get()}"
            |    const val POCKETBASE_URL = "${pocketbaseUrl.get()}"
            |}
            |""".trimMargin(),
        )
    }
}

// The merge fixtures in test-fixtures/workout-merge are shared with the backend's Node tests. Common
// tests can't read files, so they are compiled into a Kotlin source (raw strings) for commonTest.
val generateMergeFixtures = tasks.register("generateMergeFixtures") {
    val fixtures = layout.projectDirectory.dir("../test-fixtures/workout-merge")
    inputs.dir(fixtures)
    val out = layout.buildDirectory.dir("generated/mergeFixtures")
    outputs.dir(out)
    doLast {
        val file = out.get().file("dev/southstar21/volum/MergeFixtures.kt").asFile
        file.parentFile.mkdirs()
        fun literal(name: String): String {
            val text = fixtures.file(name).asFile.readText()
            require('$' !in text && "\"\"\"" !in text) { "$name: fixtures can't contain a dollar sign or triple quotes" }
            return "\"\"\"" + text + "\"\"\""
        }
        file.writeText(
            "// GENERATED by :shared:generateMergeFixtures from test-fixtures/workout-merge; do not edit.\n" +
                "package dev.southstar21.volum\n\n" +
                "internal object MergeFixtures {\n" +
                "    val merge = " + literal("merge.json") + "\n" +
                "    val mutate = " + literal("mutate.json") + "\n" +
                "}\n",
        )
    }
}

